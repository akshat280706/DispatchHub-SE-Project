import { supabase } from '../lib/supabaseClient'
import { AppError } from '../lib/errors'
import { rpcError } from '../lib/rpc'
import type { ComplaintStatus, Paged, ParcelStatus } from '../types/database'
import type { ComplaintInput } from '../schemas/complaint'

export interface ComplaintItem {
  id: string
  complaint_number: string
  subject: string
  description: string
  status: ComplaintStatus
  resolution_notes: string | null
  resolved_at: string | null
  created_at: string
  parcel_id: string
  parcel: { tracking_number: string; status: ParcelStatus; sender_name: string } | null
}

export interface ComplaintFilters {
  status: ComplaintStatus | ''
  page: number
  pageSize: number
}

const SELECT =
  'id,complaint_number,subject,description,status,resolution_notes,resolved_at,created_at,parcel_id,' +
  'parcel:parcels(tracking_number,status,sender_name)'

// Row Level Security decides which complaints the caller sees:
// a customer sees their own, a manager sees those on their branch's parcels, an admin sees all.
async function list(f: ComplaintFilters): Promise<Paged<ComplaintItem>> {
  let q = supabase.from('complaints').select(SELECT, { count: 'exact' })
  if (f.status) q = q.eq('status', f.status)
  const start = (f.page - 1) * f.pageSize
  const { data, count, error } = await q.order('created_at', { ascending: false }).range(start, start + f.pageSize - 1)
  if (error) {
    if (error.code === 'PGRST103') return { data: [], total: 0, page: f.page, pageSize: f.pageSize }
    throw new AppError('Could not load complaints.', error.code)
  }
  return {
    data: (data ?? []) as unknown as ComplaintItem[],
    total: count ?? 0,
    page: f.page,
    pageSize: f.pageSize,
  }
}

// The complaint number is generated by the database. Status always starts as OPEN.
async function create(customerId: string, input: ComplaintInput): Promise<string> {
  const { data, error } = await supabase
    .from('complaints')
    .insert({
      parcel_id: input.parcel_id,
      customer_id: customerId,
      subject: input.subject.trim(),
      description: input.description.trim(),
    })
    .select('complaint_number')
    .single()
  if (error) {
    if (error.code === '42501') throw new AppError('You can only raise complaints about your own parcels.', error.code)
    throw new AppError('Your complaint could not be sent. Please try again.', error.code)
  }
  return data.complaint_number as string
}

async function update(id: string, status: ComplaintStatus, notes: string | null): Promise<void> {
  const { error } = await supabase.rpc('update_complaint', {
    p_complaint_id: id,
    p_status: status,
    p_notes: notes,
  })
  if (error) throw rpcError(error, 'The complaint could not be updated. Please try again.')
}

export const complaintService = { listMine: list, listForReview: list, create, update }